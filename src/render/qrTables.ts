/** 18-bit version-information codeword for versions >= 7 (6 version bits + 12-bit BCH remainder). */
export function versionInfoBits(version: number): number {
  let remainder = version << 12;
  for (let bit = 17; bit >= 12; bit--) {
    if (remainder & (1 << bit)) remainder ^= 0x1f25 << (bit - 12);
  }
  return (version << 12) | remainder;
}
